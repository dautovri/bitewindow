#!/usr/bin/env python3
"""Turns the iOS string catalogue into Android string resources, so both apps share one set of
translations. Run from android/:  python3 tools/xcstrings_to_android.py

Reads  ../App/BiteWindow/Localizable.xcstrings   (never written to)
Writes app/src/main/res/values*/strings.xml and app/src/main/res/xml/locales_config.xml

A resource name is the English text in snake_case (first 48 characters). `%@` and `%lld`
become positional `%1$s` / `%2$d`. Strings in ANDROID_ONLY exist only here and are not
translated. tools/android_strings.json holds the translated strings that only the Android app
has (Google Play wording, screens iOS words differently): {name: {language: text}}, written
with the same `%@` / `%d` placeholders.
"""
import json, os, re, sys
from xml.sax.saxutils import escape

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CATALOG = os.path.join(ROOT, "..", "App", "BiteWindow", "Localizable.xcstrings")
RES = os.path.join(ROOT, "app", "src", "main", "res")
EXTRA = os.path.join(ROOT, "tools", "android_strings.json")

FOLDERS = {"pt-BR": "values-pt-rBR", "zh-Hans": "values-b+zh+Hans"}

# Text that names the iPhone. The sentence that does is left out on Android (in every
# language), rather than machine-patching a translated sentence.
DROP_SENTENCE_WITH = "iPhone"

# Not in the iOS catalogue.
ANDROID_ONLY = {"app_name": "BiteCurve", "bitecurve_pro": "BiteCurve Pro"}


def name_for(key, taken):
    slug = re.sub(r"%(\d+\$)?(@|lld|d)", "x", key.lower())
    slug = re.sub(r"[^a-z0-9]+", "_", slug).strip("_")[:48].strip("_")
    if not slug or slug[0].isdigit():
        slug = "s_" + slug
    base, n = slug, 2
    while slug in taken:
        slug = f"{base}_{n}"
        n += 1
    taken.add(slug)
    return slug


def to_android(text):
    counter = [0]

    def repl(m):
        counter[0] += 1
        pos = m.group(1)[:-1] if m.group(1) else str(counter[0])
        return f"%{pos}${'s' if m.group(2) == '@' else 'd'}"

    out = re.sub(r"%(\d+\$)?(@|lld|d)", repl, text)
    out = escape(out).replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if out[:1] in "@?":
        out = "\\" + out
    return out, counter[0]


def drop_sentence(text):
    if DROP_SENTENCE_WITH not in text:
        return text
    parts = re.split(r"(?<=[.。!?])\s*", text)
    return " ".join(p for p in parts if p and DROP_SENTENCE_WITH not in p).strip()


def main():
    strings = json.load(open(CATALOG, encoding="utf-8"))["strings"]
    extra = json.load(open(EXTRA, encoding="utf-8"))
    taken = set(ANDROID_ONLY) | set(extra)
    names = {key: name_for(key, taken) for key in strings}
    langs = sorted({l for v in strings.values() for l in v.get("localizations", {})} - {"en"})

    def write(folder, rows):
        os.makedirs(os.path.join(RES, folder), exist_ok=True)
        with open(os.path.join(RES, folder, "strings.xml"), "w", encoding="utf-8") as f:
            f.write('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/xcstrings_to_android.py from Localizable.xcstrings. Do not edit. -->\n<resources>\n')
            for name, value, translatable in rows:
                text, args = to_android(value)
                attrs = "" if translatable else ' translatable="false"'
                if args == 0 and "%" in text:
                    attrs += ' formatted="false"'
                f.write(f'    <string name="{name}"{attrs}>{text}</string>\n')
            f.write("</resources>\n")

    base = [(n, v, False) for n, v in ANDROID_ONLY.items()]
    for key, entry in strings.items():
        en = entry.get("localizations", {}).get("en", {}).get("stringUnit", {}).get("value", key)
        base.append((names[key], drop_sentence(en), True))
    base += [(name, texts["en"], True) for name, texts in extra.items()]
    write("values", base)

    missing = 0
    for lang in langs:
        rows = []
        for key, entry in strings.items():
            unit = entry.get("localizations", {}).get(lang, {}).get("stringUnit")
            if not unit or not unit.get("value"):
                missing += 1
                continue
            rows.append((names[key], drop_sentence(unit["value"]), True))
        for name, texts in extra.items():
            if texts.get(lang):
                rows.append((name, texts[lang], True))
            else:
                missing += 1
        write(FOLDERS.get(lang, f"values-{lang}"), rows)

    os.makedirs(os.path.join(RES, "xml"), exist_ok=True)
    with open(os.path.join(RES, "xml", "locales_config.xml"), "w", encoding="utf-8") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<locale-config xmlns:android="http://schemas.android.com/apk/res/android">\n')
        for lang in ["en"] + langs:
            f.write(f'    <locale android:name="{lang}" />\n')
        f.write("</locale-config>\n")

    print(f"{len(strings)} keys, {len(langs)} translations, {missing} missing")
    if "--names" in sys.argv:
        for key, name in names.items():
            print(f"{name}\t{key[:70]}")


if __name__ == "__main__":
    main()
